# Услуги без опубликованных условий. Список — не «список долгов», а
# объяснение ассистенту, почему по ним он ответит «не знаю»: условий у
# владельца на публичной странице нет.
#
# ⚠️ Условие появляется здесь ТОЛЬКО когда владелец услуги опубликовал его
# на странице, которую можно открыть и процитировать. Не по памяти, не из
# внутренних документов соседних проектов (они не публикуются — человек их
# не откроет, и цитата окажется непроверяемой).
SERVICES_WITHOUT_CONDITIONS = {
    "Радар": "Публичной страницы с условиями у сервиса нет.",
    "Футбольная школа «Интер»": "Публичной страницы с условиями у сервиса нет.",
    "Рекламный кабинет САРАФАН": "Публичной страницы с условиями у сервиса нет.",
}


def get_conditions(service_title: str) -> List[Dict[str, Any]]:
    """Условия услуги по её названию из каталога (пусто — если условий нет)."""
    return [dict(c) for c in CONDITIONS.get(service_title, [])]


def known_services() -> List[str]:
    """Названия услуг, у которых есть хотя бы одно условие."""
    return sorted(CONDITIONS)


def service_for_condition(source_ref: str) -> Optional[str]:
    """Услуга, чьё условие ссылается на этот источник (для проверки сходимости)."""
    for title, items in CONDITIONS.items():
        for item in items:
            if item["source_ref"] == source_ref:
                return title
    return None


def answer(
    service_title: str,
    question: str,
    *,
    profile_facts: Optional[List[Dict[str, Any]]] = None,
    request_id: Optional[str] = None,
) -> Dict[str, Any]:
    """Ответ по услуге в форме контракта ответа.

    Форма (план пилота #386, «Контракт ответа»):

    .. code-block:: json

        {
          "answer": [
            {"statement": "…",
             "source": {"kind": "service_condition|profile_fact|canon",
                        "ref": "…", "verified": true},
             "note": "по вашим данным"}
          ],
          "missing": ["что ещё нужно спросить у жителя"],
          "owner": "кто отвечает",
          "request_id": "…"
        }

    **Правила, которые здесь соблюдаются:**

    1. **Нет источника — нет утверждения.** Утверждение без ``source_ref`` в
       ответ не попадает. Поэтому ``source.kind`` всегда заполнен, а ``ref``
       указывает на страницу, где условие написано.
    2. **Самопровозглашённый факт** помечается «по вашим данным» и не обещает
       прав: факты приходят от сервиса-владельца (Казанская), и мы их **не
       копируем** — только цитируем по конкретному вопросу.
    3. **Нет данных ⇒ «не знаю, вот кто отвечает» + заявка**, а не тишина и не
       выдумка. Если по вопросу нет ни условия, ни факта — ответ пустой, а
       ``missing`` говорит, что спросить.
    4. **Никаких выдуманных прав** в v1 не существует.

    Пустой ``answer`` — это не поломка, а законный ответ: значит, по этому
    вопросу у нас нет данных, и мы говорим об этом прямо.
    """
    items = CONDITIONS.get(service_title, [])
    statement = (question or "").strip()
    answer_items: List[Dict[str, Any]] = []
    missing: List[str] = []

    for item in items:
        # Условие отвечает на вопрос, если вопрос совпадает с его вопросом
        # (сравнение по нормализованной строке) или это единственное условие
        # услуги — тогда оно отвечает по умолчанию, и мы честно помечаем
        # ответку как «по этому вопросу».
        if _matches(statement, item["question"]):
            answer_items.append(
                {
                    "statement": item["then"],
                    "source": {
                        "kind": "service_condition",
                        "ref": item["source_ref"],
                        "verified": True,
                    },
                    "note": None,
                    "documents": list(item["documents"]),
                    "owner": item["owner"],
                }
            )
        else:
            missing.append(item["question"])

    # Факты жителя: цитируем, не копируем. Факт без источника — не факт.
    for fact in profile_facts or []:
        source = fact.get("source") or ""
        ref = str(fact.get("ref") or "")
        if not source or not ref:
            continue
        answer_items.append(
            {
                "statement": str(fact.get("value") or ""),
                "source": {
                    "kind": "profile_fact",
                    "ref": ref,
                    "verified": fact.get("verified_at") is not None,
                },
                "note": "по вашим данным" if fact.get("verified_at") is None else None,
                "documents": [],
                "owner": str(fact.get("owner") or ""),
            }
        )

    owner = ""
    for item in items:
        if item["owner"]:
            owner = item["owner"]
            break

    # Правило 3: нет данных — «не знаю, вот кто отвечает» + заявка. Не тишина.
    if not answer_items:
        owner = owner or "Кабинет САРАФАН — +7 922 900-59-10"
        missing = missing or [statement or "уточните вопрос"]

    return {
        "version": CONTRACT_VERSION,
        "source": SOURCE_LABEL,
        "answer": answer_items,
        "missing": missing,
        "owner": owner,
        "request_id": request_id,
    }


def _matches(statement: str, question: str) -> bool:
    """Совпадает ли вопрос пользователя с вопросом условия.

    Сравнение нормализованных строк: регистр, пробелы и знаки препинания не
    различаются. Без порога «похожести» намеренно: приблизительный матч дал бы
    ответ на чужой вопрос, а это ровно тот класс отказа, который ловит
    приёмка («выдумка = провал приёмки»).
    """
    return _norm(statement) == _norm(question)


def _norm(text: str) -> str:
    out = []
    for ch in (text or "").lower():
        if ch.isalnum() or ch.isspace():
            out.append(ch)
        else:
            out.append(" ")
    return " ".join("".join(out).split())


def build_service_cards() -> List[Dict[str, Any]]:
    """Карточки услуг каталога с условиями — для витрины и для API.

    Условия в карточку входят **вместе с источником**: карточка, у которой
    условия есть, а ссылки нет, — это ровно то, что правило запрещает, но
    снаружи неотличимое от «условий нет». Поэтому в карточке всегда видно и
    условие, и его ``source_ref``.
    """
    from config.services_catalog import get_services

    cards = []
    for service in get_services():
        title = service["title"]
        cards.append(
            {
                "title": title,
                "emoji": service["emoji"],
                "url": service["url"],
                "desc": service["desc"],
                "conditions": get_conditions(title),
                "conditions_note": SERVICES_WITHOUT_CONDITIONS.get(title),
            }
        )
    return cards

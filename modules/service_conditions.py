def _condition(
    question: str,
    if_: str,
    then: str,
    documents: List[str],
    owner: str,
    source_ref: str,
) -> Dict[str, Any]:
    """Одно условие. Ключ ``if`` — имя из контракта ответа (там оно так)."""
    return {
        "question": question,
        "if": if_,
        "then": then,
        "documents": list(documents),
        "owner": owner,
        "source_ref": source_ref,
    }



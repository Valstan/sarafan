"""Карта ingest-контракта источника (вариант B, мозг одобрил #367, пилот — Казанская).

Зачем. Приёмники конвейера (портал, Казанская, Сабантуй, Культура) держат на своей
стороне список разделов, ключевых слов и правил приёма. Пока этот список жил только
в переписке и в головах, расхождение «мы шлём section=X, у них X нет» обнаруживалось
по потерянным доставкам: приёмник принимал пост без раздела с warning'ом, warning
никто не читал. Мозг 07.10 одобрил вариант B — карта у **источника**, деплой вместе
с кодом, сверка в dry-run, правдивость — контракт-тестом в CI приёмника:

    GET /api/ingest/contract

Что здесь важно и why:

- **Правда генерируется из ``SITES``, а не пишется второй раз.** Любая рукописная
  копия расходится с конфигом молча (G87: «фикс в одной копии — дивергенция»).
  Поэтому ``build_contract`` читает тот же ``config.content_conveyor.SITES``, по
  которому работает доставка, и тест сверяет выход с конфигом по полям.
- **Никаких секретов.** В контракт не попадают имена ключей (``key_env``) и их
  значения: право публиковать выражается булевым ``publishes_directly``, которое
  выводится из наличия ключа в env, а не из его имени.
- **Версия — в коде.** «Карта деплоится с кодом»: ``CONTRACT_VERSION`` живёт тут и
  меняется тем же PR, что меняет форму ответа. Приёмник может проверить «форма не
  та», не угадывая.
- **Только активные сайты.** ``get_active_sites()`` — пересечение ``SITES`` и
  ``CONVEYOR_SITES``: контракт описывает, что мы шлём СЕЙЧАС, а не что когда-то
  описали. Выключенный сайт не участник контракта — иначе приёмник готовился бы
  принять поток, который не поедет.
"""

from __future__ import annotations

from typing import Any, Dict, List

from config.content_conveyor import get_active_sites, get_batch_max, get_source_days, wants_publish

# Версия ФОРМЫ ответа (не данных). Меняется только при несовместимом изменении
# схемы — добавили поле / убрали сайт не требуют новой версии, приёмник обязан
# терпеть отсутствие необязательных полей.
CONTRACT_VERSION = "1"

# Идентификатор источника. Каноническая метка проекта по горячей линии (= setka),
# а не имя репозитория (sarafan) и не имя папки — см. ADR-0007 / hotline v1.1.
SOURCE_LABEL = "setka"


def _site_entry(site: Dict[str, Any]) -> Dict[str, Any]:
    """Описыние одного активного сайта — только то, что приёмнику нужно знать.

    ``source_owner_ids``/``source_keywords`` входят только если заданы: у сайта
    без тематической ловли (весь регион) их отсутствие — часть контракта
    («ловим всё из региона»), а не пропуск данных.
    """
    entry: Dict[str, Any] = {
        "key": str(site["key"]),
        "title": str(site.get("title") or ""),
        "source_region": str(site.get("source_region") or ""),
        # Разделы приёмника (slug'и). Неизвестный slug приёмник принимает
        # черновиком с warning — контракт фиксирует это правилом, чтобы получатель
        # не выдумывал своё поведение для одного неизвестного значения.
        "sections": [str(s) for s in (site.get("sections") or ())],
        "unknown_section": "draft-with-warning",
        # Темы, которые не доходят до приёмника вовсе (префильтр ДО LLM).
        "skip_themes": [str(s) for s in (site.get("skip_themes") or ())],
        # Право публиковать без человека. Источник — наличие ключа в env
        # (``wants_publish``), значение ключа и его имя в контракт не идут.
        "publishes_directly": bool(wants_publish(site)),
    }
    keywords = site.get("source_keywords")
    if keywords:
        entry["source_keywords"] = [str(s) for s in keywords]
    owners = site.get("source_owner_ids")
    if owners:
        entry["source_owner_ids"] = [str(o) for o in owners]
    return entry


def build_contract() -> Dict[str, Any]:
    """Собрать карту контракта из живого конфига. Чистая функция — тестируема.

    Вызывается на каждый запрос, а не кэшируется навечно: ``CONVEYOR_SITES`` и
    состав ключей могут измениться без деплоя (env), и контракт, отдающий
    прошлую правду, хуже отсутствующего. Данных тут на килобайты — считать
    на запрос дешевле, чем объяснять расхождение.
    """
    sites: List[Dict[str, Any]] = [_site_entry(s) for s in get_active_sites()]
    return {
        "version": CONTRACT_VERSION,
        "source": SOURCE_LABEL,
        "delivery": {
            # Формат тела POST на ingest-эндпойнт приёмника (правда —
            # modules/conveyor/delivery.py::build_body).
            "method": "POST",
            "fields": {
                "vkPostId": (
                    "строкой, знак сохраняется: -218991929_1057 "
                    "(id поста ВК со знаком владельца)"
                ),
                "vkPostIdSign": (
                    "знак владельца обязателен: потеря знака ломала идемпотентность (P186)"
                ),
                "sourceUrl": "URL поста-источника; основа для идемпотентности приёмника",
                "title": "заголовок до 90 символов, edited LLM",
                "text": "текст поста; отредактированный, если редактура вернулась",
                "section": "slug раздела приёмника из sections[]; поле может отсутствовать",
                "date": "ISO-8601 с Z; отсутствует, если даты у поста нет",
                "images": "URL медиа photo/doc, не больше 10; отсутствует при пустом списке",
                "publish": "true только при ключе публикации; иначе поле не шлётся",
            },
            "auth": (
                "Bearer-токен приёмника; имя переменной окружения — "
                "внутренняя конвенция, в контракт не входит"
            ),
            "idempotency": "по vkPostId: повторная доставка того же поста обновляет запись",
        },
        "limits": {
            "source_days": get_source_days(),
            "batch_max": get_batch_max(),
        },
        "sites": sites,
    }

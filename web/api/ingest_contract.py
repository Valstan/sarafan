"""HTTP-дверь карты ingest-контракта (``/api/ingest/contract``).

Вариант B пилота контракта приёмников (мозг одобрил 07.10, pool #367; опоры —
P39 против захардкоженных sections, P3 разрешает чтение, D-061 машинный обмен):
карта живёт у **источника** и деплоится вместе с кодом, поэтому приёмник никогда
не держит у себя вторую копию нашего состава разделов. Пилот — Казанская: её CI
сверяет нашу карту со своим ingest'ом в dry-run, неизвестный слаг — пропуск с
предупреждением.

Почему публично и без ключа. Ответ не содержит секретов (имена и значения ключей
намеренно не входят — см. ``modules/conveyor/contract.py``), а читать его должны
серверы приёмников, у которых cookie нашей сессии нет и не будет. Узкая поверхность:
один точный путь в ``PUBLIC_EXACT`` (не префикс — см. комментарий в
``middleware/auth_gate.py`` про почему публичные данные лежат там).
"""

from __future__ import annotations

from fastapi import APIRouter

from modules.conveyor.contract import build_contract

router = APIRouter()


@router.get("/contract")
async def contract() -> dict:
    """Карта контракта: активные сайты-получатели, разделы, ловля, лимиты.

    Считается на каждый запрос из живого конфига: ``CONVEYOR_SITES`` и состав
    ключей меняются env'ом без деплоя, и контракт обязан показывать текущую
    правду, а не ту, что была при старте процесса.
    """
    return build_contract()

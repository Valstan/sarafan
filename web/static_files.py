"""Статика, которую браузер обязан перепроверять перед показом.

Зачем это существует
--------------------

31.08 выкатили правку вёрстки, прод её принял, а браузер продолжил рисовать
старую страницу. Замер прямо на живом проде:

* сервер отдаёт новый ``style.css`` — в нём ``--navbar-h``, константы нет;
* браузер применил **старый** — ``main { margin-top: 76px }``;
* заголовки ответа: ``ETag`` есть, ``Last-Modified`` есть,
  ``Cache-Control`` — **отсутствует**.

Без ``Cache-Control`` браузер выбирает срок жизни копии сам (эвристика по
``Last-Modified``) и вправе взять её из кэша **не спрашивая сервер**. Поэтому
после деплоя посетитель может получить новый HTML и старый CSS одновременно —
а это не «часть правки не доехала», это **несогласованная пара**, которая
выглядит как разъехавшаяся вёрстка.

Отказ ровно того же класса, что и жалоба, ради которой всё затевалось:

* со стороны сервера он невидим — в логах успешная отдача свежего файла;
* он лечится сам, когда эвристический срок истечёт, поэтому к моменту разбора
  воспроизводить нечего;
* он бьёт по всем страницам разом, потому что общий стиль один.

Почему ``no-cache``, а не версии в URL
--------------------------------------

Версия в адресе (``style.css?v=20260831``) требует **помнить** её обновить.
В проекте такие метки уже есть — и часть из них протухла: ``api.js`` носит
``?v=20260808_copytext``, хотя файл с тех пор менялся. Механизм, который
работает только когда человек про него вспомнил, отказывает молча и ровно тогда,
когда правка важная.

``no-cache`` не запрещает хранить копию — он запрещает **показывать её без
переспроса**. С ``ETag`` переспрос стоит один условный запрос и ответ ``304``
без тела: для операторской панели с семью подресурсами это ничего не стоит, а
рассинхрон HTML и CSS перестаёт быть возможным состоянием.

Заголовок ставится и на ``200``, и на ``304``: ``Cache-Control`` входит в набор,
который Starlette переносит в ``NotModifiedResponse``, поэтому директива не
теряется при перепроверке.

Поправка 2026-10-14 (идея пула #250, D-096): «версии только когда человек
вспомнил» выше — про **ручные** метки, и они тем же коммитом убраны: все
``/static/``-ссылки шаблонов несут ``?v={{ STATIC_VERSION }}``, а версия
считается сама (``get_static_version``). Два слоя теперь честны каждый:
nginx отдаёт ``immutable`` по адресу, который меняется на каждом деплое,
а этот mount отдаёт ``no-cache`` для прямого доступа в обход nginx
(локальная разработка, ``:8000`` напрямую). За remnant'ы — загружаемые
файлы ``/static/broadcast/`` и ``/static/ad_offers/`` (имена те же,
содержимое меняется вне деплоев) — отвечает дата в отчёте D-096 16.10,
а не этот модуль.
"""

from __future__ import annotations

import os
import subprocess
from typing import Any

from starlette.responses import Response
from starlette.staticfiles import StaticFiles
from starlette.types import Scope

__all__ = ["RevalidatingStaticFiles", "STATIC_VERSION", "get_static_version"]


def get_static_version() -> str:
    """Версия статики для кэш-бастера ``?v=`` — из самого пакета, не руками.

    Порядок: env ``SETKA_STATIC_VERSION`` → короткий sha HEAD рабочего
    дерева → ``"dev"``. Ручные метки вида ``?v=20260831`` в шаблонах
    запрещены: константу, которую надо не забыть поднять, однажды не
    поднимают (замер — протухшие ``?v=20260522_4b`` и ``api.js?v=20260808``
    при изменённом файле). Эта функция делает адрес новым на каждом
    деплое сама — тогда ``immutable`` на nginx честен: по адресу навсегда
    те же байты и те же заголовки (идея пула #250).
    """
    forced = os.environ.get("SETKA_STATIC_VERSION", "").strip()
    if forced:
        return forced
    try:
        here = os.path.dirname(os.path.abspath(__file__))
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=here,
            capture_output=True,
            text=True,
            timeout=10,
        )
        if sha.returncode == 0 and sha.stdout.strip():
            return sha.stdout.strip()
    except Exception:
        pass
    return "dev"


#: Посчитан один раз на старте процесса — все адреса статики этого
#: деплоя одинаковы, следующий деплой даст другой sha и другие адреса.
STATIC_VERSION = get_static_version()


class RevalidatingStaticFiles(StaticFiles):
    """``StaticFiles``, отдающая ``Cache-Control: no-cache``."""

    def file_response(
        self,
        full_path: Any,
        stat_result: os.stat_result,
        scope: Scope,
        status_code: int = 200,
    ) -> Response:
        response = super().file_response(full_path, stat_result, scope, status_code)
        # super() уже мог вернуть 304 — заголовок нужен и там, иначе на следующей
        # перепроверке браузер снова останется без директивы.
        response.headers["Cache-Control"] = "no-cache"
        return response

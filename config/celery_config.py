# Worker settings
#
# **Prefetch: было 1 — и это не «минимальный расход памяти», а заморозка
# приёма очереди.** Кредит брокера (одно неподтверждённое сообщение) держит
# задача, **ждущая в пуле**: пока она не отработала, воркер не берёт из
# Redis следующую. Замер 21.11 (волна 16:40): `dispatch_ad_reposts` забрали
# в 16:43, и задача ждала в пуле 58 минут — а всё это время воркер **не
# брал из очереди ничего**: кредит был занят одной задачей, которая сама
# ждала. В логе молчание с 16:44 до 17:16, сторож сводок опоздал на 20 минут.
#
# Celery считает prefetch как (число процессов × множитель), а процесс у нас
# один — то есть было ровно 1. Теперь 4, дефолт Celery: воркер держит
# четыре неподтверждённых сообщения, и приём очереди не замирает, пока
# предыдущая задача ждёт в пуле. Память на это не растёт (payload'ы
# килобайты), а цена — при падении воркера (acks_late) на переигровку уйдут
# максимум четыре задачи вместо одной.
#
# Второй половины правки (раздельные очереди волны и периодики) — в
# [ADR-0020](../docs/adr/0020-ochered-volny-i-periodika.md) и в
# `config/runtime.py::get_wave_queue`.
worker_prefetch_multiplier = 4
# Переработка дочернего процесса пула. Было 1000 — и это, а не «опция не задана»,
# оказалось настоящим диагнозом OOM-убийств (найдено 2026-09-14).
#
# **Замер на проде, а не оценка.** Воркер завершает 250–380 задач в час (среднее
# ~300, считано по строкам «succeeded in» за сутки), ядро одно → concurrency 1 →
# дочерний процесс ровно один. При пороге 1000 он переживает **3.3 часа**, а
# ядро убивает его раньше: по `dmesg` восемь OOM-убийств за 09.09–14.09, RSS в
# момент смерти 390–518 МБ при 1536 МБ на боксе и **swap = 0**. Свежий ребёнок
# занимает ~87 МБ, то есть память копится до потолка внутри одного интервала
# переработки — порог просто не успевает сработать.
#
# 250 задач ≈ 50 минут при нынешнем темпе: ребёнок перерабатывается втрое чаще,
# чем растёт до опасного размера. Цена — форк с ре-импортом приложения примерно
# раз в час на 7000 задач в сутки; на фоне 1 ядра это шум.
#
# Почему не через `--max-tasks-per-child` в ExecStart юнита: конфиг уже здесь и
# уже применяется (`app.config_from_object("config.celery_config")`). Вторая
# копия настройки в юните на проде создала бы два места правды, и первое же
# расхождение искали бы в коде, а не в systemd.
#
# Это лечение накопления, а не его причины. Течь (что именно копит память) не
# найдена — порог лишь не даёт ей дорасти до убийства. См. PENDING.
worker_max_tasks_per_child = 250

# Потолок памяти дочернего процесса (в килобайтах — так требует Celery).
# Второй предохранитель к порогу по задачам (2026-09-22, заказ владельца
# «почему не хватает памяти»). Что он делает и чего НЕ делает:
#
# * Celery сравнивает с порогом **пиковый** RSS (``ru_maxrss``) после
#   завершения каждой задачи. Одиночный всплеск внутри задачи он не остановит,
#   но как только ребёнок хоть раз перерос порог — он перерабатывается сразу
#   после этой задачи, чисто, форком, а не SIGKILL от ядра посреди
#   ``wall.post``.
# * **350 → 200 МБ (21.11, P164).** Прежний порог стоял **ВЫШЕ** точки, где
#   убивает ядро: замер 19.11 — ядро сняло ребёнка (celery) на anon-rss
#   **327 МБ**, а порог был 350 МБ, то есть штатная переработка не наступала
#   **никогда**, и выигрывал всегда ядро. Отсюда и «убитый ребёнок уносит
#   пачку задач»: ребёнка убивали не до ребра порога, а до края.
#   Ребёнок растёт ~13 МБ/мин (свежий — ~87 МБ), поэтому 200 МБ он
#   достигает через ~9 мин и перерождается сам, за ~127 МБ до точки убийства.
#   Размен — вдвое больше форков (каждый — форк и пересоздание пула asyncpg за
#   несколько секунд) против реже идущих жертв ядра.
# * ⚠️ Потолок **не** спасает от всплеска внутри задачи: измеренный пик
#   вечерней сводки — 332 МБ, это тот самый пояс, где ядро бьёт. Задача,
#   которая держит столько, чинится отдельно (см. PENDING).
#
# Срабатывает тот из двух порогов, что наступит первым.
#
# Снимок бокса 2026-09-22, подтверждающий выбор: ``nproc`` = 1, дочерний
# процесс РОВНО ОДИН (значит потолок не умножается на число детей), и за 23
# минуты жизни он уже занимал **268 МБ** при 324 МБ свободных на боксе. То
# есть между нормальной работой и полосой убийств зазор меньше сотни мегабайт,
# и порог ложится в него: ребёнок переработается сам, не дожидаясь ядра.
worker_max_memory_per_child = 200 * 1024

# Ограничение времени задачи. Ядро одно, concurrency 1: зависшая задача
# (сокет ВК, замок в БД) блокирует ВСЕ beat-задачи, включая поминутные
# диспетчеры. Жёсткий лимит убивает дочерний процесс — ровно то же, что делает
# ядро при OOM, и этот отказ система уже переносит: ``task_acks_late`` вместе с
# ``task_reject_on_worker_lost`` возвращают задачу в очередь.
#
# **Мягкого лимита здесь НЕТ, и это осознанный отказ, а не недосмотр.**
# Почти все задачи синхронные снаружи и асинхронные внутри: они крутят корутину
# через ``utils/celery_asyncio.run_coro``, то есть ``loop.run_until_complete``
# на ОДНОМ персистентном цикле процесса (иначе пул asyncpg разваливается —
# см. докстринг того модуля). ``SoftTimeLimitExceeded`` прилетает сигналом в
# тот же поток и выбрасывает управление из ``run_until_complete``, но саму
# корутину НЕ отменяет: она остаётся висеть на общем цикле. Задача при этом
# «завершается» ошибкой, воркер берёт следующую — и недобитая корутина
# продолжает исполняться вперемежку с ней, держа соединение из пула (размер 3)
# и досылая свои побочные действия, вплоть до публикации. Получилось бы, что
# защита от зависания порождает отказ страшнее зависания, и притом молчаливый.
# Жёсткий лимит такого не умеет: он убивает процесс целиком вместе с циклом.
#
# **Границы взяты из замера, а не на глаз** (журналы воркера, 2026-09-22,
# максимум по каждой задаче за двое суток):
#
#   1750 с  recheck_all_active_regions  ← недельный обход, СВОИ лимиты в задаче
#    368 с  parse_and_publish_theme
#    310 с  classify_pending_posts
#    230 с  refresh_post_metrics
#    103 с  check_recent_comments
#
# То есть у всего, что ходит по расписанию чаще раза в неделю, запас
# девятикратный. Единственная задача, которой общего лимита мало, объявляет
# свой прямо в декораторе (``tasks/discovery_tasks.py``) — там же и почему.
task_time_limit = 3600

# Очереди публикационных слотов.
#
# **Замер 25.11 00:20 — общая очередь `celery` оказалась кладбищем, и в ней
# молча умерли две волны и лента хаба.**
#
# Что было на боксе в 00:20 (живой замер, не оценка):
#
# | Что | Факт |
# |---|---|
# | Очередь `celery` | **467 сообщений**, все с истёкшим сроком (хвост — с истечением 22:02) |
# | Состав | `dispatch_ad_reposts` 144, `dispatch_broadcasts` 144, лента 21, веер волны 2 |
# | Воркер | вместо выполнения — `Discarding revoked task` (**3434 раза** в одном логе) |
# | Волна `admin` (22:20) | веер лежал в `celery` с `expires` 23:20 → **истекла, волна не вышла** |
# | Волна `sport` (22:50) | то же, `expires` 23:50 → **истекла** |
# | Лента хаба (раз в 5 мин) | отброшена как просроченная в 00:00:20 — **лента встала** |
# | Вечерняя сводка | **выжила**: своя очередь `digest` + `expires` 7200 — 48 регионов |
#
# Механизм: общая очередь — FIFO, а разбирает её **тот же единственный слот**, что
# занят длинными задачами сводки (1–3 минуты на регион). Скорость разбора — доли
# задачи в минуту, скорость поступления — три задачи в минуту (поминутные
# диспетчеры). Очередь растёт, а всё, у кого короткий `expires`, в ней протухает.
# Отбрасывание просроченного — **INFO**: в логе на 11 МБ это одна строка, а слот
# пропадает целиком и без единой ошибки.
#
# **Решение: публикационные слоты живут в очереди `wave`, а не в общей `celery`.**
# Именно эти две задачи бьют по сети и по времени: веер волны (81 задача на
# регион) и лента хаба. Очередь `wave` обслуживают оба воркера
# (`--queues=celery,wave,digest` и `--queues=wave,digest`), и в неё **никогда не
# попадает** мелкая периодика — а значит, слот публикации не стоит в заторе.
#
# Прочая мелкая периодика (диспетчеры репостов, сторожи, классификатор) остаётся
# в `celery` — это её штатное место, и поднимать её срок в очереди нельзя: тогда
# кладбище будет расти быстрее.
#
# Откат — одна строка в env бокса: `SETKA_WAVE_QUEUE=celery` + рестарт beat и
# воркеров. Код трогать не нужно.
task_routes = {
    # Веер волны: задача-«мама», из которой рождаются задачи регионов.
    "tasks.parsing_scheduler_tasks.run_all_regions_theme": {"queue": get_wave_queue()},
    # Публикация по региону и лента хаба (раз в 5 минут).
    "tasks.parsing_scheduler_tasks.parse_and_publish_theme": {"queue": get_wave_queue()},
}

